        private struct EncodeEntry
        {
            public ulong Code;
            public byte BitCount;
        }

        private static readonly EncodeEntry[] EncTable;
        // Дерево декодирования: узел u хранит [child_bit_0, child_bit_1] по индексам u*2 и u*2 + 1.
        // Значение > 0 — индекс дочернего узла; значение < 0 — лист с символом (-val - 1).
        private static readonly int[] DecTree;

        static HuffmanCodec()
        {
            EncTable = new EncodeEntry[257];
            var nodes = new List<int[]> { new int[2] };

            for (int sym = 0; sym < 257; sym++)
            {
                int bitLen = RawHuffmanTable[sym * 2];
                int bitVal = RawHuffmanTable[sym * 2 + 1];

                EncTable[sym] = new EncodeEntry
                {
                    Code = (ulong)bitVal,
                    BitCount = (byte)bitLen
                };

                int curr = 0;
                for (int b = bitLen - 1; b >= 0; b--)
                {
                    int bit = (bitVal >> b) & 1;
                    if (b == 0)
                    {
                        nodes[curr][bit] = -(sym + 1);
                    }
                    else
                    {
                        int next = nodes[curr][bit];
                        if (next == 0)
                        {
                            next = nodes.Count;
                            nodes.Add(new int[2]);
                            nodes[curr][bit] = next;
                        }
                        curr = next;
                    }
                }
            }

            DecTree = new int[nodes.Count * 2];
            for (int i = 0; i < nodes.Count; i++)
            {
                DecTree[i * 2] = nodes[i][0];
                DecTree[i * 2 + 1] = nodes[i][1];
            }
        }

        private int _bitNum = 8;
        private int _value;
        private int _mask;
        private int _treePos;

        public void Reset()
        {
            _bitNum = 8;
            _value = 0;
            _mask = 0;
            _treePos = 0;
        }

        /// <summary>
        /// Распаковывает входящий сжатый поток байтов от сервера.
        /// Возвращает количество распакованных байтов в dest.
        /// </summary>
        public bool Decompress(ReadOnlySpan<byte> src, Span<byte> dest, out int written)
        {
            written = 0;
            int destCapacity = dest.Length;

            while (true)
            {
                if (_bitNum >= 8)
                {
                    if (src.IsEmpty)
                    {
                        return true;
                    }

                    _value = src[0];
                    src = src.Slice(1);
                    _bitNum = 0;
                    _mask = 0x80;
                }

                int bit = (_value & _mask) != 0 ? 1 : 0;
                _treePos = DecTree[_treePos * 2 + bit];

                _mask >>= 1;
                _bitNum++;

                if (_treePos < 0)
                {
                    int sym = (-_treePos) - 1;
                    if (sym == 256)
                    {
                        _bitNum = 8;
                        _treePos = 0;
                        continue;
                    }

                    if (written >= destCapacity)
                    {
                        return false;
                    }

                    dest[written++] = (byte)sym;
                    _treePos = 0;
                }
            }
        }

        /// <summary>
        /// Сжимает байты пакета для передачи по сети (используется встроенным сервером).
        /// Добавляет терминальный символ конца блока (256) и выравнивает до байта.
        /// </summary>
        public static bool Compress(ReadOnlySpan<byte> src, Span<byte> dest, out int written)
        {
            written = 0;
            int bitAccumulator = 0;
            int bitsInAccumulator = 0;

            for (int i = 0; i < src.Length; i++)
            {
                EncodeEntry entry = EncTable[src[i]];
                WriteBits(entry.Code, entry.BitCount, ref bitAccumulator, ref bitsInAccumulator, dest, ref written);
            }

            // Завершающий символ UO Huffman (256)
            EncodeEntry term = EncTable[256];
            WriteBits(term.Code, term.BitCount, ref bitAccumulator, ref bitsInAccumulator, dest, ref written);

            // Выравнивание последнего байта
            if (bitsInAccumulator > 0)
            {
                bitAccumulator <<= (8 - bitsInAccumulator);
                if (written >= dest.Length) return false;
                dest[written++] = (byte)bitAccumulator;
            }

            return true;
        }

        private static void WriteBits(ulong code, byte count, ref int acc, ref int bitsInAcc, Span<byte> dest, ref int written)
        {
            for (int i = count - 1; i >= 0; i--)
            {
                int bit = (int)((code >> i) & 1);
                acc = (acc << 1) | bit;
                bitsInAcc++;

                if (bitsInAcc == 8)
                {
                    if (written < dest.Length)
                    {
                        dest[written++] = (byte)acc;
                    }
                    acc = 0;
                    bitsInAcc = 0;
                }
            }
        }
