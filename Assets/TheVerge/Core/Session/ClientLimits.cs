namespace TheVerge.Core.Session
{
    /// <summary>
    /// Настройки самого клиента, которых нет на сервере: пределы, таймауты, бюджеты. Единственное место этих чисел
    /// в коде клиента; документ — docs/TARGET.md §3.1 «Настройки клиента», решение — ADR 0013.
    /// Лимиты сервера — в <see cref="ServerLimits"/>.
    /// </summary>
    public static class ClientLimits
    {
        /// <summary>
        /// Сколько байт с места ошибки попадает в дамп, когда длина пакета неизвестна (неизвестный номер, сломанная
        /// длина). Если длина известна, в дамп идёт весь пакет.
        /// </summary>
        public const int ErrorDumpBytes = 256;

        /// <summary>
        /// Предел очереди целых пакетов от сокета к главному потоку, байт. Как network.sendBufferMaxSize сервера
        /// (NetState.Network.cs): полная очередь останавливает чтение сокета, и сервер сам отключает клиента.
        /// </summary>
        public const int InboundQueueBytes = 2 * 1024 * 1024;

        /// <summary>Сколько ждать ответа сервера на подключение, мс.</summary>
        public const int ConnectTimeoutMs = 10000;

        /// <summary>
        /// Сколько мс за тик разбирать пришедшие пакеты (из 16,7 мс кадра при 60 FPS). Не меньше одного пакета за тик:
        /// очередь движется, даже если один пакет обрабатывается дольше бюджета.
        /// </summary>
        public const int TickBudgetMs = 5;

        /// <summary>
        /// Предел одного файла лога пакетов, символов (для текста лога это почти байты): 64 МБ. Дальше лог не делится на
        /// части — одна сессия остаётся одним файлом для фейкового сервера; запись останавливается строкой «#truncated».
        /// </summary>
        public const long PacketLogMaxChars = 64L * 1024 * 1024;
        /// <summary>
        /// Язык клиента, который он сообщает серверу после входа (сервер пишет его в Mobile.Language и ставит в речь
        /// персонажа). ENU — как у классического клиента по умолчанию; тексты cliloc выбирает сам клиент.
        /// </summary>
        public const string Language = "ENU";
        /// <summary>
        /// Пауза между ping в мире, мс. Сервер отключает после 30 с без обмена данными (NetState.cs, CheckAlive): треть
        /// предела переживёт два потерянных ping.
        /// </summary>
        public const int PingIntervalMs = 10000;
        /// <summary>Сколько ждать ответа сервера на выход, мс; дальше клиент закрывает соединение сам.</summary>
        public const int LogoutTimeoutMs = 5000;
        /// <summary>Сколько ждать ответа сервера во время входа (список, редирект, вход в мир), мс; дальше — ошибка.</summary>
        public const int ServerResponseTimeoutMs = 30000;
        /// <summary>
        /// Паузы перед повторами входа, мс (не удалось подключиться, разрыв в мире): нарастают вдвое; сколько пауз, столько
        /// попыток. Дольше 16 с человек решит сам.
        /// </summary>
        public static readonly int[] ReconnectDelaysMs = { 1000, 2000, 4000, 8000, 16000 };
    }
}
