namespace TheVerge.Core.Session
{
    /// <summary>
    /// Настройки самого клиента, которых нет на сервере: пределы, таймауты, бюджеты. Единственное место этих чисел
    /// в коде клиента; документ — docs/TARGET.md §3.1 «Настройки клиента», решение — ADR 0013.
    /// Лимиты сервера — в <see cref="ServerLimits"/>.
    /// </summary>
    public static class ClientLimits
    {
        /// <summary>
        /// Сколько байт с места ошибки попадает в дамп, когда длина пакета неизвестна (неизвестный номер, сломанная
        /// длина). Если длина известна, в дамп идёт весь пакет.
        /// </summary>
        public const int ErrorDumpBytes = 256;

        /// <summary>
        /// Предел очереди целых пакетов от сокета к главному потоку, байт. Как network.sendBufferMaxSize сервера
        /// (NetState.Network.cs): полная очередь останавливает чтение сокета, и сервер сам отключает клиента.
        /// </summary>
        public const int InboundQueueBytes = 2 * 1024 * 1024;

        /// <summary>Сколько ждать ответа сервера на подключение, мс.</summary>
        public const int ConnectTimeoutMs = 10000;

        /// <summary>
        /// Сколько мс за тик разбирать пришедшие пакеты (из 16,7 мс кадра при 60 FPS). Не меньше одного пакета за тик:
        /// очередь движется, даже если один пакет обрабатывается дольше бюджета.
        /// </summary>
        public const int TickBudgetMs = 5;

        /// <summary>
        /// Предел одного файла лога пакетов, символов (для текста лога это почти байты): 64 МБ. Дальше лог не делится на
        /// части — одна сессия остаётся одним файлом для фейкового сервера; запись останавливается строкой «#truncated».
        /// </summary>
        public const long PacketLogMaxChars = 64L * 1024 * 1024;
        /// <summary>
        /// Язык клиента, который он сообщает серверу после входа (сервер пишет его в Mobile.Language и ставит в речь
        /// персонажа). ENU — как у классического клиента по умолчанию; тексты cliloc выбирает сам клиент.
        /// </summary>
        public const string Language = "ENU";

        /// <summary>
        /// Цвет своей речи (0xAD). Сервер приводит его к допустимому (Utility.ClipDyedHue); 0x02B2 — как у ClassicUO по
        /// умолчанию, сверить после 0.6 (docs/TARGET.md §3.1).
        /// </summary>
        public const ushort SpeechHue = 0x02B2;
        /// <summary>
        /// Пауза между ping в мире, мс. Сервер отключает после 30 с без обмена данными (NetState.cs, CheckAlive): треть
        /// предела переживёт два потерянных ping.
        /// </summary>
        public const int PingIntervalMs = 10000;
        /// <summary>Сколько ждать ответа сервера на выход, мс; дальше клиент закрывает соединение сам.</summary>
        public const int LogoutTimeoutMs = 5000;

        /// <summary>
        /// Удалять объекты дальше дальности обзора, когда свой персонаж сдвинулся. Сервер 0x1D за оставшимися позади не
        /// шлёт (Mobile.SetLocation), поэтому по умолчанию включено; выключение — только для отладки (docs/TARGET.md §3.1).
        /// </summary>
        public const bool RemoveOutOfRange = true;
        /// <summary>Сколько ждать ответа сервера во время входа (список, редирект, вход в мир), мс; дальше — ошибка.</summary>
        public const int ServerResponseTimeoutMs = 30000;
        /// <summary>
        /// Паузы перед повторами входа, мс (не удалось подключиться, разрыв в мире): нарастают вдвое; сколько пауз, столько
        /// попыток. Дольше 16 с человек решит сам.
        /// </summary>
        public static readonly int[] ReconnectDelaysMs = { 1000, 2000, 4000, 8000, 16000 };
        /// <summary>
        /// Сколько персонаж должен пробыть в мире после повтора, чтобы попытки считались заново, мс. Сервер выгоняет
        /// «неверный клиент» через 20 с после входа (clientVerification.kickDelay, docs/TARGET.md §3.1): со сбросом сразу при
        /// входе такой выгон повторялся бы без конца.
        /// </summary>
        public const int ReconnectStableMs = 60000;

        /// <summary>Адрес логин-сервера на экране входа по умолчанию — локальный стенд (AGENTS.md §1).</summary>
        public const string DefaultServerAddress = "127.0.0.1:2593";

        /// <summary>
        /// Сколько последних боевых событий (замахи, анимации, урон, эффекты, звуки) держит журнал боя; старые вытесняются.
        /// Бой с крысой — около 50 событий за 20 с: хватает на несколько минут боя.
        /// </summary>
        public const int CombatLogCapacity = 512;

        /// <summary>
        /// Шагов и поворотов без ответа сервера, после которых клиент ждёт ответа (PLAN Стадия 3, п. 5). Как у ClassicUO
        /// (MAX_STEP_COUNT = 5): при пинге около 430 мс бег верхом идёт по расписанию сервера, а поворот и шаг за ним уходят
        /// в одном тике (с 3 шаг ждал ответа). Сервер сбрасывает свою очередь шагов при
        /// <see cref="ServerLimits.ServerStepQueueLimit"/> — вдвое больше; темп отправки по-прежнему по расписанию сервера.
        /// </summary>
        public const int MaxUnacknowledgedSteps = 5;

        /// <summary>
        /// Сколько ждать вторую клавишу перед первым шагом из покоя, мс (PLAN Стадия 3, п. 1; CONTROLS §4): пару клавиш
        /// (W+D) никогда не нажимают ровно одновременно, а без ожидания первый шаг ушёл бы прямо, а не по диагонали.
        /// </summary>
        public const int MovePairWaitMs = 50;

        /// <summary>
        /// Опоздание шага на столько мс (тик кадра или бота пришёл позже срока) догоняется: следующий шаг идёт по расписанию,
        /// а не через полную задержку от фактического. Большее опоздание — игрок стоял — не копится (PLAN Стадия 3, п. 7).
        /// Не больше 50: с ним клиент не опережает расписание сервера и не тратит его запас на джиттер.
        /// </summary>
        public const int MoveCatchUpMs = 50;

        /// <summary>Во сколько раз быстрее, самое большее, показывается шаг, когда картинка отстала (ADR 0020 п. 4).</summary>
        public const int StepCatchUpMaxSpeedup = 2;

        /// <summary>
        /// Рывок больше стольких клеток между двумя соседними клетками от сервера — перескок, а не езда (ADR 0020 п. 5). Пачку
        /// соседних шагов после лага картинка догоняет, а не перескакивает (её ограничивает <see cref="StepBacklogSnapMs"/>).
        /// </summary>
        public const int StepSnapGapCells = 2;

        /// <summary>
        /// Картинка чужого моба отстала от последней клетки сервера больше чем на столько мс (остаток текущего шага и ждущие
        /// шаги по обычному времени) — перескок на эту клетку (ADR 0020 п. 5). Лаг 500 мс и самый долгий шаг (400 мс) —
        /// 900 мс — помещаются: всплеск лага догоняется без перескока; место секундной давности в бою хуже перескока.
        /// </summary>
        public const int StepBacklogSnapMs = 1000;

        /// <summary>
        /// Режим «симуляция пинга» (PLAN Стадия 3, п. 9; ADR 0020 п. 9): задержка по умолчанию в каждую сторону, мс. 50 туда и
        /// 50 обратно — пинг около 100 мс, середина целевого диапазона ADR 0020 (до 200 мс).
        /// </summary>
        public const int LagSimulationDefaultDelayMs = 50;

        /// <summary>Разброс по умолчанию в каждую сторону, ± мс: в сумме ±30 мс, как в целях ADR 0020.</summary>
        public const int LagSimulationDefaultJitterMs = 15;

        /// <summary>Наибольшая задержка в одну сторону, мс: всплеск лага 500 мс (критерии Стадии 3) помещается с запасом.</summary>
        public const int LagSimulationMaxDelayMs = 1000;

        /// <summary>Наибольший разброс в одну сторону, ± мс.</summary>
        public const int LagSimulationMaxJitterMs = 500;
    }
}
